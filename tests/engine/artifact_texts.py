def game_text(
    text: str,
    *,
    buttons: tuple[Button, ...] = (),
    at: datetime | None = None,
    msg_id: int = 1,
) -> IncomingMessage:
    """Новое сообщение игры в её чате; `at` — дата (по умолчанию сейчас)."""
    moment = at or datetime.now(UTC)
    return IncomingMessage(
        chat_id=GAME,
        msg_id=msg_id,
        revision=0,
        kind="new",
        date=moment,
        received_at=moment,
        text=text,
        inline=buttons,
        from_id=GAME,
        created_at=moment,
    )
