def startup_msg(
    text: str,
    *,
    buttons: tuple[Button, ...] = (),
    msg_id: int = 1,
) -> IncomingMessage:
    """Новое сообщение игры в её чате с этим текстом."""
    moment = datetime(2026, 10, 8, 7, 0, tzinfo=UTC)
    return IncomingMessage(
        chat_id=GAME,
        msg_id=msg_id,
        revision=0,
        kind="new",
        date=moment,
        received_at=moment,
        text=text,
        inline=buttons,
        from_id=GAME,
        created_at=moment,
    )
