def options(*counts: int) -> tuple[Button, ...]:
    """Кнопки количества в один ряд, как у игры."""
    return tuple(
        Button(text=str(n), row=0, col=i, data=f"g_tangerines_small_{n}")
        for i, n in enumerate(counts)
    )


def gift_msg(
    text: str,
    *,
    buttons: tuple[Button, ...] = (),
    msg_id: int = 1,
    revision: int = 0,
) -> IncomingMessage:
    """Сообщение игры в её чате с этим текстом (`revision` > 0 — правка)."""
    moment = datetime(2026, 10, 8, 7, 0, tzinfo=UTC)
    return IncomingMessage(
        chat_id=GAME,
        msg_id=msg_id,
        revision=revision,
        kind="edit" if revision else "new",
        date=moment,
        received_at=moment,
        text=text,
        inline=buttons,
        from_id=GAME,
        created_at=moment,
    )
